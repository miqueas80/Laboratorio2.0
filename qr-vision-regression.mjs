import fs from 'node:fs';
import path from 'node:path';
const root=path.dirname(new URL(import.meta.url).pathname);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const checks=[];
const pass=(name,ok)=>checks.push([ok?'PASS':'FAIL',name]);
pass('QR view exists',html.includes('id="view-qr"'));
pass('Independent Vision view exists',html.includes('id="view-vision"'));
pass('Vision camera has dedicated video element',html.includes('id="visionVideo"'));
pass('Vision camera has explicit permission control',html.includes('id="visionPermissionBtn"'));
pass('QR has dedicated stream state',app.includes('state.stream'));
pass('Vision has independent stream state',app.includes('state.visionStream'));
pass('QR stop stops every track',/function stopQr\(\).*?state\.stream\.getTracks\(\)\.forEach\(t=>t\.stop\(\)\)/s.test(app));
pass('QR detection calls processQr',/if\(raw\)\{state\.scanBusy=true;processQr\(raw\);return\}/.test(app));
pass('QR result stops camera',/function processQr\(raw\).*?stopQr\(\)/s.test(app));
pass('QR result contains no captured image',/function processQr\(raw\).*?qrResult.*?innerHTML/s.test(app) && !/processQr\(raw\)[\s\S]{0,1200}canvasToDataUrl/.test(app));
pass('BarcodeDetector failure falls back to jsQR',/if\(!raw\)raw=await decodeQrVideoFrame/.test(app));
pass('QR image decode falls back to jsQR when BarcodeDetector misses',/if\(codes\[0\]\?\.rawValue\)\{bitmap\.close\(\);processQr/.test(app));
pass('OCR no longer binds to QR camera button',!app.includes("$('#ocrCameraBtn').onclick"));
pass('Vision camera requests camera permission',app.includes('requestVisionCameraPermission'));
pass('Vision camera start is separate from QR start',app.includes('startVisionCamera') && app.includes('startQr'));
pass('Vision analysis uses vision video',/analyzeCurrentVisionCamera\(\)[\s\S]*?#visionVideo/.test(app));
pass('Agent can open Vision module',app.includes("'open_vision'"));
pass('Agent can start Vision camera',app.includes("'start_vision_camera'"));
pass('Agent can stop Vision camera',app.includes("'stop_vision_camera'"));
pass('Agent can analyze Vision camera',app.includes("'analyze_vision_camera'"));
pass('Generic analyze_camera is routed to Vision, not QR',/if\(type==='analyze_camera'\)\{setView\('vision'\);const r=await analyzeCurrentVisionCamera/.test(app));
pass('QR has no OCR UI block',!/<h3[^>]*>🔎 Visión NEXUS-X/.test(html));
pass('Vision view contains OCR UI',html.includes('id="ocrOutput"') && html.includes('id="substanceAnalysis"'));

let failed=0;for(const [s,n] of checks){console.log(`${s} ${n}`);if(s==='FAIL')failed++;}
console.log(`\nQR/VISION REGRESSION: ${checks.length-failed} passed, ${failed} failed`);
process.exitCode=failed?1:0;
